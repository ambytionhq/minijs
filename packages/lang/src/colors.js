/** @type {ReadonlySet<string>} */
const NAMED = new Set(CSS_COLOR_NAMES)
const HEX = /^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i

/**
 * Named color or `#rgb` / `#rrggbb`, case-insensitive.
 * @param {string} value
 * @returns {boolean}
 */
export function isCssColor(value) {
  return HEX.test(value) || NAMED.has(value.toLowerCase())
}

/**
 * Join color words (`sky blue` -> `skyblue`) and return the lowercase color, or null if it is not one.
 * @param {string[]} words
 * @returns {string | null}
 */
export function normalizeColor(words) {
  if (words.length === 0) return null
  const joined = words.join('').toLowerCase()
  return isCssColor(joined) ? joined : null
}
